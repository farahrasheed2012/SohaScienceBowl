        "                let bounds = segment.split(separator: \"–\").compactMap { Int($0.trimmingCharacters(in: .whitespaces)) }",
        "                if bounds.count == 2, bounds[0] <= bounds[1] {",
        "                    result.append(contentsOf: bounds[0]...bounds[1])",
        "                    continue",
        "                }",
        "            }",
