        "        let name: String",
        "        let startPage: Int",
        "    }",
        "",
        "    struct Section: Hashable {",
        "        let id: String",
        "        let title: String",
        "    }",
        "",
        "    struct Chapter: Hashable {",
        "        let number: Int",
        "        let title: String",
        "        let part: PartInfo",
        "        let startPage: Int",
        "        let sections: [Section]",
        "    }",
        "",
        "    struct Appendix: Hashable {",
        "        let letter: String",
        "        let title: String",
        "        let startPage: Int",
        "    }",
        "",
        '    static let editionTitle = "Conceptual Physical Science Explorations (Hewitt et al.)"',
        "",
